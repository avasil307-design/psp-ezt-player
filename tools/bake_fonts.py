#!/usr/bin/env python3
"""Bake Roboto + Material Symbols Rounded into a single 8-bit alpha atlas.

Outputs:
  assets/atlas.bin  - EZ_ATLAS_W x EZ_ATLAS_H alpha bytes
  assets/atlas.h    - glyph table + style metrics (no pixels)

Requires: pillow, fonttools (tools/requirements.txt).
Fonts come from tools/fetch_fonts.sh -> build/fonts/.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets")
FONTS = os.path.join(ROOT, "build", "fonts")

ATLAS_W, ATLAS_H = 512, 512

LATIN = "".join(chr(c) for c in range(0x20, 0x7F))
CYRILLIC = (
    "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
    "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
)
EXTRA = "«»—–…·№°"

STYLES = [
    ("Roboto-Medium.ttf", 24, "EZ_T24M"),
    ("Roboto-Regular.ttf", 16, "EZ_T16"),
    ("Roboto-Medium.ttf", 16, "EZ_T16M"),
    ("Roboto-Regular.ttf", 12, "EZ_T12"),
    ("Roboto-Medium.ttf", 12, "EZ_T12M"),
]
ICON_STYLES = [(24, "EZ_I24"), (18, "EZ_I18"), (14, "EZ_I14")]

ICONS = [
    "play_arrow", "pause", "skip_next", "skip_previous", "settings", "folder",
    "movie", "palette", "check", "arrow_back", "more_vert", "grid_view",
    "fullscreen", "volume_up", "dark_mode", "light_mode", "chevron_left",
    "chevron_right", "playlist_play", "history", "home", "search", "image",
    "videocam", "smart_display", "play_circle", "close", "refresh", "tune",
    "speed", "subdirectory_arrow_right",
]


class Packer:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.x, self.y, self.shelf_h = 1, 1, 0

    def add(self, w, h):
        if self.x + w + 1 > self.w:
            self.x = 1
            self.y += self.shelf_h + 1
            self.shelf_h = 0
        if self.y + h + 1 > self.h:
            raise RuntimeError("atlas overflow")
        pos = (self.x, self.y)
        self.x += w + 1
        self.shelf_h = max(self.shelf_h, h)
        return pos


def icon_codepoints():
    cmap = TTFont(os.path.join(FONTS, "MaterialSymbolsRounded.ttf")).getBestCmap()
    by_name = {}
    for cp, gname in cmap.items():
        by_name.setdefault(gname, cp)
    out = {}
    for name in ICONS:
        if name in by_name:
            out[name] = by_name[name]
        else:
            print("WARN: icon not found:", name)
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    atlas = Image.new("L", (ATLAS_W, ATLAS_H), 0)
    packer = Packer(ATLAS_W, ATLAS_H)
    glyphs = []   # (style, cp, ox, oy, ax, ay, w, h, adv)
    metrics = []  # (ascent, descent)

    def bake_glyph(style_idx, cp, font):
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        if cp == 0x20:
            glyphs.append((style_idx, cp, 0, 0, 0, 0, 0, 0, adv))
            return
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            glyphs.append((style_idx, cp, 0, 0, 0, 0, 0, 0, adv))
            return
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        ax, ay = packer.add(w, h)
        atlas.paste(img, (ax, ay))
        glyphs.append((style_idx, cp, x0, y0, ax, ay, w, h, adv))

    for style_idx, (fname, size, _enum) in enumerate(STYLES):
        font = ImageFont.truetype(os.path.join(FONTS, fname), size)
        metrics.append(font.getmetrics())
        for ch in LATIN + CYRILLIC + EXTRA:
            bake_glyph(style_idx, ord(ch), font)

    icons = icon_codepoints()
    icons_path = os.path.join(FONTS, "MaterialSymbolsRounded.ttf")
    for k, (size, _enum) in enumerate(ICON_STYLES):
        style_idx = len(STYLES) + k
        font = ImageFont.truetype(icons_path, size)
        metrics.append(font.getmetrics())
        for name in ICONS:
            if name in icons:
                bake_glyph(style_idx, icons[name], font)

    with open(os.path.join(OUT, "atlas.bin"), "wb") as f:
        f.write(atlas.tobytes())

    glyphs.sort(key=lambda g: (g[0] << 16) | g[1])
    enum_names = [s[2] for s in STYLES] + [s[1] for s in ICON_STYLES]

    with open(os.path.join(OUT, "atlas.h"), "w") as f:
        f.write("/* Generated by tools/bake_fonts.py - do not edit. */\n")
        f.write("#ifndef EZ_ATLAS_DATA_H\n#define EZ_ATLAS_DATA_H\n\n")
        f.write("#define EZ_ATLAS_W %d\n#define EZ_ATLAS_H %d\n" % (ATLAS_W, ATLAS_H))
        f.write("#define EZ_STYLE_COUNT %d\n" % len(metrics))
        f.write("/* icon codepoints */\n")
        for name, cp in sorted(icons.items()):
            f.write("#define EZ_IC_%s 0x%04X\n" % (name, cp))
        f.write("\n")
        for i, name in enumerate(enum_names):
            f.write("#define %s %d\n" % (name, i))
        f.write("\nstatic const ez_style_metric ez_style_metrics[EZ_STYLE_COUNT] = {\n")
        for ascent, descent in metrics:
            f.write("    {%d, %d},\n" % (ascent, descent))
        f.write("};\n\n#define EZ_GLYPH_COUNT %d\n" % len(glyphs))
        f.write("static const ez_glyph ez_glyphs[EZ_GLYPH_COUNT] = {\n")
        f.write("    /* style, cp, ox, oy, ax, ay, w, h, adv */\n")
        for g in glyphs:
            f.write("    {%d,%d,%d,%d,%d,%d,%d,%d,%d},\n" % g)
        f.write("};\n\n#endif\n")

    print("atlas %dx%d, %d glyphs, %d styles, used height %d"
          % (ATLAS_W, ATLAS_H, len(glyphs), len(metrics), packer.y + packer.shelf_h))


if __name__ == "__main__":
    sys.exit(main())
